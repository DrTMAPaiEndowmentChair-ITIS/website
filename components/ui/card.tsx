import * as React from "react"

import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn("ring-foreground/10 bg-card/88 text-card-foreground overflow-hidden rounded-2xl text-xs/relaxed ring-1 shadow-[0_1px_0_rgba(255,255,255,.5)_inset] backdrop-blur-sm has-[>img:first-child]:pt-0 *:[img:first-child]:rounded-t-2xl *:[img:last-child]:rounded-b-2xl group/card flex flex-col", className)}
      {...props}
    />
  )
}

